export function drawCaptcha(answer: string) {
  const lines = Array.from({ length: 5 }, () => {
    const x1 = randomInt(5, 225);
    const y1 = randomInt(4, 66);
    const x2 = randomInt(5, 225);
    const y2 = randomInt(4, 66);
    return `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="#b987ad" stroke-width="1" opacity=".6"/>`;
  }).join("");

  const letters = [...answer].map((letter, index) => {
    const glyph = glyphs[letter];
    if (!glyph) throw new Error("Unsupported CAPTCHA character");
    const x = 25 + index * 42 + randomInt(-3, 4);
    const y = 16 + randomInt(-4, 5);
    const angle = randomInt(-10, 11);
    const pixels = glyph.flatMap((row, rowIndex) => [...row].flatMap((pixel, columnIndex) =>
      pixel === "1" ? [`<rect x="${columnIndex * 5}" y="${rowIndex * 5}" width="5" height="5"/>`] : [],
    )).join("");
    return `<g transform="translate(${x} ${y}) rotate(${angle} 12.5 17.5)" fill="#422147">${pixels}</g>`;
  }).join("");

  return `<svg xmlns="http://www.w3.org/2000/svg" width="230" height="70" viewBox="0 0 230 70"><rect width="230" height="70" rx="8" fill="#f8edf4"/>${lines}${letters}</svg>`;
}
